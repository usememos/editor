// Writes src/emoji/data.ts, the emoji the `emoji()` extension offers, from
// the gemoji package: GitHub's emoji names (MIT). Run it after updating
// gemoji: `node packages/editor/scripts/emoji-data.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gemoji } from 'gemoji';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(createRequire(import.meta.url).resolve('gemoji/package.json'), 'utf8'));
// One line per emoji: the emoji, its names, its tags, separated by tabs; names and tags by spaces.
const lines = gemoji.map((g) => [g.emoji, g.names.join(' '), g.tags.join(' ')].join('\t'));
writeFileSync(
  join(pkg, 'src/emoji/data.ts'),
  `// Generated by scripts/emoji-data.mjs from gemoji ${version}: GitHub's emoji names (MIT). Do not edit.
// One line per emoji: the emoji, its names, its tags, separated by tabs.

export const EMOJI_DATA: string = ${JSON.stringify(lines.join('\n'))};
`,
);
console.log(`${lines.length} emoji`);
